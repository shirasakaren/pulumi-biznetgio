#!/usr/bin/env python3
"""post-codegen patch: java codegen derives group from basePackage and uses the
legacy Sonatype staging API. rewrite gradle files to publish
ren.shirasaka:biznetgio via the Central Portal publishing plugin."""
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else "sdk/java")

(root / "build.gradle").write_text("""// *** WARNING: this file is generated by pulumi-java-gen and post-processed by scripts/fix-java-gradle.py ***
// Publishes ren.shirasaka:biznetgio to Maven Central via the Central Portal API.

plugins {
    id("signing")
    id("java-library")
    id("maven-publish")
    id("de.marcphilipp.gradle.central-publishing") version "0.4.0"
}

java {
    withSourcesJar()
    withJavadocJar()
    toolchain {
        languageVersion = JavaLanguageVersion.of(11)
    }
}

group = "ren.shirasaka"
version = System.getenv("PACKAGE_VERSION") ?: "0.0.1"

repositories {
    mavenCentral()
}

dependencies {
    implementation("com.google.code.findbugs:jsr305:3.0.2")
    implementation("com.google.code.gson:gson:2.8.9")
    implementation("com.pulumi:pulumi:1.0.0")
}

def genPulumiResources = tasks.register('genPulumiResources') {
    doLast {
        def resourcesDir = sourceSets.main.output.resourcesDir
        def subDir = project.name.replace(".", "/")
        def outDir = file("$resourcesDir/$subDir")
        outDir.mkdirs()
        new File(outDir, "version.txt").text = project.version
        def builder = new groovy.json.JsonBuilder()
        builder {
            resource true
            name "biznetgio"
            server "github://api.github.com/shirasakaren/pulumi-biznetgio"
            version project.version
        }
        new File(outDir, "plugin.json").text = builder.toPrettyString()
    }
}

jar.configure {
    dependsOn genPulumiResources
}

publishing {
    publications {
        mainPublication(MavenPublication) {
            artifactId = "biznetgio"
            from components.java
            artifact sourcesJar
            artifact javadocJar

            pom {
                name = "pulumi-biznetgio"
                description = "Unofficial Pulumi provider for Biznet GIO cloud by Shirasaka Ren — NEO Metal, NEO Lite/Lite Pro, NEO GPU, and Object Storage."
                url = "https://github.com/shirasakaren/pulumi-biznetgio"

                licenses {
                    license {
                        name = "The Apache License, Version 2.0"
                        url = "http://www.apache.org/licenses/LICENSE-2.0.txt"
                    }
                }

                developers {
                    developer {
                        id = "shirasakaren"
                        name = "Shirasaka Ren"
                        email = "ren@shirasaka.ren"
                    }
                }

                scm {
                    connection = "scm:git:https://github.com/shirasakaren/pulumi-biznetgio.git"
                    developerConnection = "scm:git:https://github.com/shirasakaren/pulumi-biznetgio.git"
                    url = "https://github.com/shirasakaren/pulumi-biznetgio"
                }
            }
        }
    }
}

centralPortal {
    username = System.getenv("PUBLISH_REPO_USERNAME")
    password = System.getenv("PUBLISH_REPO_PASSWORD")
}

def signingKey = System.getenv("JAVA_SIGNING_KEY")
if (signingKey != null && !signingKey.isEmpty()) {
    signing {
        useInMemoryPgpKeys(System.getenv("JAVA_SIGNING_KEY_ID"), signingKey, System.getenv("JAVA_SIGNING_PASSWORD"))
        sign publishing.publications.mainPublication
    }
}
""")

s = (root / "settings.gradle").read_text()
s = s.replace('rootProject.name = "ren.shirasaka.biznetgio.biznetgio"',
              'rootProject.name = "ren.shirasaka.biznetgio"')
(root / "settings.gradle").write_text(s)
print("patched java gradle files (central portal publishing)")
